#!/usr/bin/env node
// Build the browser copy of the workbench engine.
//
// The engine is written once, as import-free-of-Node ES modules in
// archi-made-easy/workbench/. This script wraps each module in its own function scope and
// emits one classic-script fragment, viewer/workbench-engine.js, that the viewer template
// inlines. `--check` fails when the committed fragment is stale. A parity test
// (test/workbench-engine-parity.test.mjs) proves both copies give identical results.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { sameEntry } from '../archi-made-easy/renderers/shared/path-semantics.mjs';

const defaultRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** Modules in dependency order (a module may import only from earlier ones). */
export const ENGINE_MODULES = [
  'defaults.mjs', 'model.mjs', 'sim.mjs', 'cost.mjs', 'scenarios.mjs', 'fmea.mjs', 'review.mjs', 'compare.mjs', 'remedy.mjs',
  'exporters/shared.mjs', 'exporters/mermaid.mjs', 'exporters/drawio.mjs', 'exporters/structurizr.mjs', 'exporters/rfc.mjs',
];

/** Public surface of ArchiMadeEasy.workbenchEngine: export name -> module. */
export const ENGINE_API = {
  buildModel: 'model.mjs', applyAlternative: 'model.mjs',
  simulate: 'sim.mjs', FAULT_STATES: 'sim.mjs',
  estimateCost: 'cost.mjs',
  buildScenarios: 'scenarios.mjs', runScenario: 'scenarios.mjs', breachReach: 'scenarios.mjs',
  buildFmea: 'fmea.mjs',
  review: 'review.mjs', RULES: 'review.mjs', PILLARS: 'review.mjs',
  compareDesigns: 'compare.mjs', compareAlternatives: 'compare.mjs',
  applyPatches: 'remedy.mjs', figures: 'remedy.mjs', compareFigures: 'remedy.mjs', previewPatches: 'remedy.mjs', recoveryOptions: 'remedy.mjs', recoveryPlan: 'remedy.mjs',
  toMermaidMarkdown: 'exporters/mermaid.mjs', toDrawio: 'exporters/drawio.mjs', toStructurizr: 'exporters/structurizr.mjs', toRfc: 'exporters/rfc.mjs',
};

const IMPORT_RE = /^import\s+\{([^}]+)\}\s+from\s+'(\.[^']+)';[ \t]*$/gm;
const EXPORT_RE = /^export\s+(?:async\s+)?(function|const|let|class)\s+([A-Za-z_$][\w$]*)/gm;

function transform(source, key) {
  const names = [];
  let body = source.replace(IMPORT_RE, (whole, list, specifier) => {
    const target = path.posix.normalize(path.posix.join(path.posix.dirname(key), specifier));
    if (!ENGINE_MODULES.includes(target)) throw new Error(`${key}: imports ${specifier}, which is not an engine module`);
    if (ENGINE_MODULES.indexOf(target) >= ENGINE_MODULES.indexOf(key)) throw new Error(`${key}: imports ${target}, which is not earlier in ENGINE_MODULES`);
    const bindings = list.split(',').map((item) => item.trim()).filter(Boolean).map((item) => item.replace(/\s+as\s+/, ': '));
    return `var { ${bindings.join(', ')} } = __modules[${JSON.stringify(target)}];`;
  });
  body = body.replace(EXPORT_RE, (whole, kind, name) => { names.push(name); return whole.replace(/^export\s+/, ''); });
  if (/^\s*import\s/m.test(body)) throw new Error(`${key}: an import form the generator does not understand remains`);
  if (/^\s*export\s/m.test(body)) throw new Error(`${key}: an export form the generator does not understand remains`);
  return { body: body.replace(/\s+$/, ''), names };
}

export function buildEngine({ root = defaultRoot } = {}) {
  const sourceRoot = path.join(root, 'archi-made-easy', 'workbench');
  const exported = new Map();
  const parts = [
    '// Generated by scripts/generate-workbench-engine.mjs from archi-made-easy/workbench/. Do not edit by hand.',
    '// Regenerate with: npm --prefix archi-made-easy run generate:workbench-engine',
    'ArchiMadeEasy.workbenchEngine = (function () {',
    '  var __modules = {};',
  ];
  for (const key of ENGINE_MODULES) {
    const { body, names } = transform(fs.readFileSync(path.join(sourceRoot, key), 'utf8').replace(/\r\n/g, '\n'), key);
    exported.set(key, names);
    parts.push(`  // ---- ${key}`, `  __modules[${JSON.stringify(key)}] = (function () {`, "    'use strict';", body, `    return { ${names.join(', ')} };`, '  })();');
  }
  const api = Object.entries(ENGINE_API).map(([name, module]) => {
    if (!exported.get(module)?.includes(name)) throw new Error(`ENGINE_API: ${module} does not export ${name}`);
    return `    ${name}: __modules[${JSON.stringify(module)}].${name},`;
  });
  parts.push('  return {', ...api, '  };', '})();', '');
  const fragment = parts.join('\n');
  // The artifact gate counts this exact substring anywhere in the page, including scripts.
  if (/<svg\b/.test(fragment)) throw new Error('engine fragment must not contain the literal "<svg"');
  if (/<\/script/i.test(fragment)) throw new Error('engine fragment must not contain a closing script tag');
  // Artifact validation (for example the architecture delta page) rejects a page whose text
  // contains these bare names, wherever they appear. Engine modules use
  // Number.POSITIVE_INFINITY and Number.isNaN instead.
  if (/\b(?:NaN|Infinity)\b/.test(fragment)) throw new Error('engine fragment must not contain the bare names NaN or Infinity');
  // Parse check: the fragment must be valid classic-script code.
  // eslint-disable-next-line no-new-func
  new Function('ArchiMadeEasy', fragment);
  return fragment;
}

export function generateWorkbenchEngine({ root = defaultRoot, check = false } = {}) {
  const outputPath = path.join(root, 'viewer', 'workbench-engine.js');
  const generated = buildEngine({ root });
  if (check) {
    const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8').replace(/\r\n/g, '\n') : null;
    if (current !== generated) throw new Error('Workbench engine fragment is stale. Run: npm --prefix archi-made-easy run generate:workbench-engine');
    return { outputPath, changed: false };
  }
  fs.writeFileSync(outputPath, generated);
  return { outputPath, changed: true };
}

if (process.argv[1] && sameEntry(process.argv[1], fileURLToPath(import.meta.url)).status === 'match') {
  try {
    const check = process.argv.includes('--check');
    generateWorkbenchEngine({ check });
    console.log(check ? 'workbench engine fragment is up to date' : 'generated viewer/workbench-engine.js');
  } catch (error) {
    console.error(error.message);
    process.exit(1);
  }
}
